-- Execute no SQL Editor do projeto Supabase.
create table if not exists public.characters (
  player_id text primary key,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
create table if not exists public.app_state (
  key text primary key,
  data jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  message_type text not null default 'text',
  author text not null default 'Mesa',
  data jsonb not null default '{}'::jsonb
);

alter table public.characters enable row level security;
alter table public.app_state enable row level security;
alter table public.chat_messages enable row level security;

-- Mesa aberta sem login: políticas públicas. Qualquer pessoa com acesso ao link
-- e à chave anon poderá ler/escrever; não é autenticação nem proteção contra fraude.
drop policy if exists "public read characters" on public.characters;
create policy "public read characters" on public.characters for select to anon, authenticated using (true);
drop policy if exists "public write characters" on public.characters;
create policy "public write characters" on public.characters for all to anon, authenticated using (true) with check (true);
drop policy if exists "public read app_state" on public.app_state;
create policy "public read app_state" on public.app_state for select to anon, authenticated using (true);
drop policy if exists "public write app_state" on public.app_state;
create policy "public write app_state" on public.app_state for all to anon, authenticated using (true) with check (true);
drop policy if exists "public read chat" on public.chat_messages;
create policy "public read chat" on public.chat_messages for select to anon, authenticated using (true);
drop policy if exists "public insert chat" on public.chat_messages;
create policy "public insert chat" on public.chat_messages for insert to anon, authenticated with check (true);
drop policy if exists "public delete chat" on public.chat_messages;
create policy "public delete chat" on public.chat_messages for delete to anon, authenticated using (true);

